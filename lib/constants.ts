export function sampleAudioSources(fileName: string): { src: string; type: string }[] {
  const base = fileName.replace(/\.(wav|mp3|m4a|ogg)$/i, "");
  return [
    { src: `/samples/${base}.wav`, type: "audio/wav" },
    { src: `/samples/${base}.m4a`, type: "audio/mp4" },
  ];
}
