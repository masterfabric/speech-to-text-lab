export function resolveSampleId(fileName: string): string {
  const lower = fileName.toLowerCase();
  const base = lower.replace(/\.(wav|mp3|m4a|ogg)$/i, "");
  const byStem = [...SAMPLE_CATALOG].sort(
    (a, b) => b.fileName.length - a.fileName.length,
  );
  for (const sample of byStem) {
    const stem = sample.fileName.replace(/\.(wav|mp3|m4a|ogg)$/i, "").toLowerCase();
    if (base === stem || base.endsWith("/" + stem) || lower.includes(stem)) {
      return sample.id;
    }
  }
  const byId = [...SAMPLE_CATALOG].sort((a, b) => b.id.length - a.id.length);
  for (const sample of byId) {
    if (lower.includes(sample.id.toLowerCase())) return sample.id;
  }
  if (lower.includes("silence")) return "default";
  return "default";
}

